using System.Text;

namespace Abox.Kits;

/// <summary>
/// Turns a workload into a sandbox kit: a descriptor and the Dockerfile the image is built from.
/// </summary>
public sealed class WorkloadKitGenerator
{
    /// <summary>The name of the generated descriptor, without the extension.</summary>
    public const string KitName = "workload";

    /// <summary>The directory the scripts of the workload are copied into.</summary>
    public const string ScriptsDirectoryName = "scripts";

    /// <summary>The BuildKit secret the GitHub token is passed as, so it stays out of the layers.</summary>
    public const string GitHubTokenSecret = "github_token";

    /// <summary>
    /// Writes the kit into a directory, replacing what was there before.
    /// </summary>
    public void Generate(WorkloadFile workload, string targetDirectory)
    {
        Directory.CreateDirectory(targetDirectory);

        WriteDescriptor(workload, targetDirectory);
        WriteDockerfile(workload, targetDirectory);
        CopyScripts(workload, targetDirectory);
    }

    private static void WriteDescriptor(WorkloadFile workload, string targetDirectory)
    {
        var descriptor = new StringBuilder()
            .AppendLine("# syntax=docker/sandbox-kit:3")
            .AppendLine("schemaVersion: \"3\"")
            .AppendLine("kind: workload")
            .AppendLine($"displayName: {workload.Name}")
            .AppendLine(
                $"description: The base image built from {Path.GetFileName(workload.Path)}."
            )
            .AppendLine("capabilities:")
            .AppendLine("  - type: com.docker.sandbox/sbx@1")
            .ToString();

        File.WriteAllText(Path.Combine(targetDirectory, KitName + ".yaml"), descriptor);
    }

    private static void WriteDockerfile(WorkloadFile workload, string targetDirectory)
    {
        var dockerfile = new StringBuilder()
            .AppendLine("# syntax=docker/dockerfile:1")
            .AppendLine(
                $"# Generated by abox from {Path.GetFileName(workload.Path)}. Change the workload, not this file."
            )
            .AppendLine($"FROM {workload.Template}")
            .AppendLine()
            .AppendLine("# mise manages the tools of this image.")
            .AppendLine(
                "ENV PATH=\"/home/agent/.local/bin:/home/agent/.local/share/mise/shims:${PATH}\""
            )
            .AppendLine("RUN if ! command -v mise >/dev/null 2>&1; then \\")
            .AppendLine("      curl -fsSL https://mise.run | sh; \\")
            .AppendLine("    fi")
            .AppendLine();

        if (workload.Apt.Count > 0)
        {
            var install = new StringBuilder()
                .AppendLine("    apt-get update \\")
                .AppendLine(
                    "    && DEBIAN_FRONTEND=noninteractive apt-get install -y --no-install-recommends \\"
                );

            foreach (var package in workload.Apt)
            {
                install.AppendLine($"    {package} \\");
            }

            install.Append("    && apt-get clean && rm -rf /var/lib/apt/lists/*");

            dockerfile
                .AppendLine("# The apt packages are installed in one step, system before tools.")
                .AppendLine("RUN \\")
                .Append(install.ToString())
                .AppendLine()
                .AppendLine();
        }

        if (workload.Mise.Count > 0)
        {
            dockerfile
                .AppendLine(
                    "# One install step per tool, so a tool that runs into a rate limit does not hold up the others."
                )
                .AppendLine(
                    "# The versions of a tool are installed in one step, in reverse order, because mise activates the first entry of its list."
                );

            foreach (var (tool, versions) in GroupTools(workload.Mise))
            {
                dockerfile
                    .AppendLine($"RUN --mount=type=secret,id={GitHubTokenSecret},required=false \\")
                    .AppendLine(
                        $"    GITHUB_TOKEN=\"$(cat /run/secrets/{GitHubTokenSecret} 2>/dev/null || true)\" \\"
                    )
                    .AppendLine($"    mise use -g -y {string.Join(' ', versions)}");
            }

            dockerfile.AppendLine();
        }

        if (workload.Scripts.Count > 0)
        {
            dockerfile
                .AppendLine("# The scripts of the workload run while the image is built.")
                .AppendLine($"COPY {ScriptsDirectoryName}/ /tmp/abox-{ScriptsDirectoryName}/");

            foreach (var script in workload.Scripts)
            {
                dockerfile.AppendLine(
                    $"RUN bash /tmp/abox-{ScriptsDirectoryName}/{Path.GetFileName(script)}"
                );
            }

            dockerfile.AppendLine();
        }

        dockerfile.AppendLine("WORKDIR /home/agent/workspace");

        File.WriteAllText(
            Path.Combine(targetDirectory, KitName + ".dockerfile"),
            dockerfile.ToString()
        );
    }

    /// <summary>
    /// The tools of a workload, grouped by tool. The versions of one tool are installed in
    /// one step, so mise keeps them all, and the list is reversed, so the version that
    /// comes last in the workload is the one mise activates.
    /// </summary>
    internal static IReadOnlyList<(string Tool, IReadOnlyList<string> Versions)> GroupTools(
        IReadOnlyList<string> specs
    )
    {
        var groups = new List<(string Tool, List<string> Versions)>();
        var byTool = new Dictionary<string, List<string>>(StringComparer.Ordinal);

        foreach (var spec in specs)
        {
            var (tool, _) = Split(spec);

            if (!byTool.TryGetValue(tool, out var versions))
            {
                versions = [];
                byTool[tool] = versions;
                groups.Add((tool, versions));
            }

            versions.Add(spec);
        }

        // The groups come in reverse order too, so the tool of the last entry of the
        // workload is the one mise activates.
        return groups
            .AsEnumerable()
            .Reverse()
            .Select(group =>
                (
                    group.Tool,
                    (IReadOnlyList<string>)group.Versions.AsEnumerable().Reverse().ToList()
                )
            )
            .ToList();
    }

    /// <summary>The tool of a spec and the version it asks for.</summary>
    private static (string Tool, string Version) Split(string spec)
    {
        var at = spec.LastIndexOf('@');
        return at > 0 ? (spec[..at], spec[(at + 1)..]) : (spec, string.Empty);
    }

    private static void CopyScripts(WorkloadFile workload, string targetDirectory)
    {
        var scriptsDirectory = Path.Combine(targetDirectory, ScriptsDirectoryName);

        if (Directory.Exists(scriptsDirectory))
        {
            Directory.Delete(scriptsDirectory, recursive: true);
        }

        if (workload.Scripts.Count == 0)
        {
            return;
        }

        Directory.CreateDirectory(scriptsDirectory);

        foreach (var script in workload.Scripts)
        {
            var source = Path.Combine(workload.Directory, script);
            if (!File.Exists(source))
            {
                throw new AboxException(
                    $"The script '{script}' of '{workload.Path}' does not exist."
                );
            }

            File.Copy(
                source,
                Path.Combine(scriptsDirectory, Path.GetFileName(script)),
                overwrite: true
            );
        }
    }
}
