"""
tools/ado_tools.py — Strands @tool wrappers for Azure DevOps work items.

Follows the factory pattern from AI-Azure-Agent/src/agent/tools/ado_tools.py:
tools are closures over a shared AzureDevOpsClient + Settings instance so auth
and policy are set up once.
"""
from __future__ import annotations

import json
import sys
import os
from typing import Any

from strands import tool

sys.path.insert(0, os.path.dirname(os.path.dirname(__file__)))
from ado_client import AzureDevOpsClient
from redact import redact_text
from schemas import Settings

AI_COMMENT_MARKER = "[AI-generated by CAPE BAU Support Agent]"


def _write_guard(settings: Settings, action_enabled: bool, action_name: str) -> str | None:
    """Check whether a write action is permitted by the current settings.

    Returns None if the action is allowed, or an error message string if it is
    blocked. The caller should return that string as {"ok": false, "error": ...}
    without executing the operation.
    """
    if not settings.ado_writes_enabled:
        return "Write actions are disabled by policy (ado_writes_enabled=false)."
    if not action_enabled:
        return f"{action_name} is disabled by policy."
    return None


def create_ado_tools(
    client: AzureDevOpsClient,
    settings: Settings,
    include_write_tools: bool = True,
) -> list[Any]:
    """Return Strands tool list backed by *client* and governed by *settings*.

    Args:
        include_write_tools: When False, only fetch_ado_ticket is returned —
            used by the triage stage (agent.py's create_triage_agent), which
            never writes to ADO and should not even be offered the tools, not
            just policy-guarded against using them.
    """

    @tool
    def fetch_ado_ticket(
        work_item_id: int,
        include_comments: bool = False,
        comments_limit: int = 5,
    ) -> str:
        """Fetch an ADO work item and return its key fields as JSON.

        Args:
            work_item_id: Numeric ADO work item ID.
            include_comments: Whether to include recent comments (default False).
            comments_limit: How many comments to fetch when include_comments is True
                (default 5).

        Returns:
            JSON string with id, type, title, state, tags, description (raw HTML,
            PII-redacted — see redact.py), wiki_links (extracted from the
            description HTML before redaction), and optionally comments (also
            redacted).
        """
        raw = client.get_work_item(work_item_id)
        fields = raw.get("fields", {})
        desc_html = fields.get("System.Description", "") or ""
        # Structural extraction runs on the ORIGINAL html — hrefs and the DQC
        # name in the title are not PII and redacting first would only risk
        # breaking the regexes below on placeholder text.
        wiki_links = AzureDevOpsClient.extract_wiki_links_from_html(desc_html)
        dqc_name = AzureDevOpsClient.extract_dqc_name_from_title(
            fields.get("System.Title", "")
        )
        # PII redaction (names/emails/phones/IBANs) happens last, right before
        # the text is put into the payload the model sees. See redact.py for
        # why this is Presidio/NER-based rather than a naive signature-block
        # cut (rejected 2026-09-15 — risks dropping real ticket content).
        desc_html = redact_text(desc_html)

        # Squad = the leaf segment of System.AreaPath (e.g. "CS\CaRMen\AC" -> "AC").
        # Falls back to None when the area path has no recognisable squad leaf
        # (matches the bau-task-analysis skill's "unresolved" convention).
        area_path = fields.get("System.AreaPath", "") or ""
        area_leaf = area_path.rsplit("\\", 1)[-1] if area_path else ""
        squad = area_leaf if area_leaf in {"AC", "BC", "CC", "MOD"} else None

        def _identity_name(field: str) -> str | None:
            value = fields.get(field)
            if isinstance(value, dict):
                return value.get("displayName")
            return value or None

        payload: dict[str, Any] = {
            "id": raw.get("id"),
            "type": fields.get("System.WorkItemType"),
            "title": fields.get("System.Title"),
            "state": fields.get("System.State"),
            "tags": fields.get("System.Tags"),
            "description": desc_html,
            "wiki_links_in_description": wiki_links,
            "dqc_subscription_name": dqc_name,
            "url": AzureDevOpsClient.html_url(raw),
            # Stakeholder fields — authoritative (ADO fields), per the
            # bau-task-analysis skill's step 1 "Stakeholders" split. Prose-based
            # mentions (e.g. "loop in Jane from BC") are NOT extracted here —
            # that requires reading the description text, which the model does
            # itself from the returned description/comments.
            "created_by": _identity_name("System.CreatedBy"),
            "assigned_to": _identity_name("System.AssignedTo"),
            "area_path": area_path,
            "squad": squad,
        }

        if include_comments:
            raw_comments = client.get_work_item_comments(work_item_id, comments_limit)
            payload["comments"] = [
                {
                    "text": redact_text(c.get("text", "")),
                    "date": c.get("createdDate", ""),
                }
                for c in raw_comments
            ]

        return json.dumps(payload, ensure_ascii=False, indent=2)

    @tool
    def add_comment_to_ticket(work_item_id: int, comment_text: str) -> str:
        """Post a comment to an ADO work item.

        Args:
            work_item_id: Numeric ADO work item ID.
            comment_text: Markdown-formatted comment body.

        Returns:
            JSON confirmation with comment ID and timestamp, or an error if writes
            are disabled by policy.
        """
        guard_message = _write_guard(
            settings, settings.ado_comments_write_enabled, "Comment updates"
        )
        if guard_message:
            return json.dumps({"ok": False, "error": guard_message})

        full_text = f"{comment_text.strip()}\n\n{AI_COMMENT_MARKER}"
        result = client.add_comment(work_item_id, full_text)
        return json.dumps(
            {
                "ok": True,
                "comment_id": result.get("id"),
                "created": result.get("createdDate"),
            }
        )

    @tool
    def set_azure_devops_ticket_ai_checked_tag(
        work_item_id: int, tag: str = "AI-checked"
    ) -> str:
        """Add a tag to an ADO work item while preserving existing tags.

        Args:
            work_item_id: Numeric ADO work item ID.
            tag: Tag to add (default "AI-checked").

        Returns:
            JSON confirmation with the merged tag string, or an error if writes
            are disabled by policy.
        """
        guard_message = _write_guard(
            settings, settings.ado_tags_write_enabled, "Tag updates"
        )
        if guard_message:
            return json.dumps({"ok": False, "error": guard_message})

        result = client.ensure_work_item_tag(work_item_id, tag)
        return json.dumps(
            {
                "ok": True,
                "work_item_id": work_item_id,
                "tag": tag,
                "tags": result.get("tags"),
                "updated": result.get("updated", True),
            }
        )

    return [fetch_ado_ticket] if not include_write_tools else [
        fetch_ado_ticket,
        add_comment_to_ticket,
        set_azure_devops_ticket_ai_checked_tag,
    ]
