"""
agent.py — CAPE BAU Support Agent assembly and entry point.

Usage:
    python3 agent.py <work_item_id>                 # legacy single-stage flow
    python3 agent.py <work_item_id> --triage-only    # triage stage only (recommended)

Two run modes, sharing the same ADO client and wiki tools:

1. Triage-only (--triage-only, recommended): runs create_triage_agent() on a
   cheap model (schemas.Settings.bedrock_model_id, default an eu-central-1
   Claude Haiku inference profile — see _build_model()'s docstring),
   covering steps 1-3 of the opencode `bau-task-analysis` skill (fetch,
   extract identifiers/stakeholders, classify, decide needs_deep_analysis).
   Prints ONLY the raw JSON result to stdout — no comment formatting, no ADO
   write. Meant to be invoked as an external process by the bau-task-analysis
   skill's step 0, which parses stdout and continues to that skill's
   deep-analysis stage (steps 4-5, stronger model) only when
   needs_deep_analysis is true.
2. Legacy single-stage (no flag): the original flow — fetches, classifies,
   looks up the wiki, AND formats+optionally posts an ADO comment in one run.
   Kept for standalone use; not the entry point the two-stage pipeline calls.

Architecture overview
---------------------
The file has three layers:

1. Helpers (_extract_json, _format_comment)
   Pure functions — no ADO access, no side effects. Testable in isolation.

2. Agent factories (create_agent, create_triage_agent)
   Wire up the model, tools, and system prompt into a Strands Agent object.
   Kept separate so tests or callers can inject a different client or settings.

3. Runtime (run_triage, run_agent, __main__)
   Owns the full lifecycle: Settings → client → agent → response → (comment →
   post, legacy only). This is the only layer that touches ADO and has side
   effects.

Redaction of ticket text (PII) happens inside fetch_ado_ticket
(tools/ado_tools.py calling redact.py), not in this file — see prompts.py's
module docstring and redact.py for details.
"""
from __future__ import annotations

import json
import re
import sys
import os

from strands import Agent
from strands.models.bedrock import BedrockModel
# strands.models.openai (and the 'openai' package it wraps) is imported
# lazily inside _build_model()'s github_copilot branch instead of here -
# 'openai' is NOT installed by the sandbox's strands kit by default (it's
# the legacy/dev-only, currently-broken provider), so importing it
# unconditionally at module load would break the default Bedrock path too.

# Make the parent directory importable so sibling modules (ado_client, schemas,
# prompts, tools/) resolve correctly regardless of where Python is launched from.
sys.path.insert(0, os.path.dirname(__file__))
from ado_client import AzureDevOpsClient
from schemas import Settings
from prompts import CAPE_BAU_AGENT_SYSTEM_PROMPT, CAPE_BAU_TRIAGE_SYSTEM_PROMPT
from tools.ado_tools import create_ado_tools
from tools.wiki_tools import create_wiki_tools

AI_COMMENT_MARKER = "[AI-generated by CAPE BAU Support Agent]"


# ---------------------------------------------------------------------------
# Helpers
# ---------------------------------------------------------------------------

def _extract_json(text: str) -> dict:
    """Extract the JSON result object from the agent's response text.

    The prompt instructs the agent to return a JSON object, optionally wrapped
    in a ```json ... ``` fenced code block. We try the fenced form first (more
    reliable), then fall back to the first bare {...} block in the text.

    Raises ValueError if neither pattern matches, or json.JSONDecodeError if
    the matched text isn't valid JSON.
    """
    match = re.search(r"```(?:json)?\s*(\{.*?\})\s*```", text, re.DOTALL)
    if match:
        return json.loads(match.group(1))
    match = re.search(r"\{.*\}", text, re.DOTALL)
    if match:
        return json.loads(match.group(0))
    raise ValueError("No JSON object found in agent response")


def _format_comment(result: dict) -> str:
    """Render the agent's JSON result dict as a markdown ADO comment string.

    The four keys from the JSON schema (summary, success, failure_cause,
    next_steps) are laid out as a readable first-response comment. Only
    non-empty optional fields (failure_cause, next_steps) are included.
    The AI marker is appended as a footer so ADO can identify agent comments.
    """
    lines = ["## CAPE BAU Support Agent — First Response", ""]

    status = "✅ Resolved" if result.get("success") else "❌ Escalation needed"
    lines += [f"**Status:** {status}", ""]

    if summary := result.get("summary"):
        lines += ["**Summary:**", "", summary, ""]

    if failure_cause := result.get("failure_cause"):
        lines += ["**Could not resolve:**", "", failure_cause, ""]

    if next_steps := result.get("next_steps"):
        lines += ["**Next steps:**", "", next_steps, ""]

    lines += ["---", f"*{AI_COMMENT_MARKER}*"]
    return "\n".join(lines)


# ---------------------------------------------------------------------------
# Model selection
# ---------------------------------------------------------------------------

def _build_model(settings: Settings):
    """Build the LLM model object for settings.model_provider.

    'bedrock' (default, production — verified working end-to-end 2026-09-07):
    BedrockModel against the eu-central-1 cross-region inference profile,
    authenticated via ambient AWS credentials (SSO session / IAM role already
    available in the sandbox via the 'aws' kit + cs-nonprod profile locally,
    or the sandbox's own AWS credential setup) — no token to manage, no
    egress-allowlist gap. Replaces GitHub Copilot as the sole model provider,
    not just a documented fallback: see 'github_copilot' below for why.

    'github_copilot' (legacy/dev, currently BROKEN): GitHub Copilot's
    OpenAI-compatible endpoint categorically rejects a raw PAT for its Chat
    Completions API — confirmed 401 across all three tried auth-header
    schemes. The normal flow needs a copilot_internal/v2/token exchange
    first, which itself needs api.github.com — not on the sandbox's egress
    allowlist. Kept only for local experimentation if a working Copilot OAuth
    token becomes available. See the 2026-09-07 bau-triage handoff for the
    full investigation.
    """
    if settings.model_provider == "github_copilot":
        # Lazy import: 'openai' is not installed by default (see the import
        # comment at the top of this file) - only needed for this branch.
        from strands.models.openai import OpenAIModel
        copilot_token = settings.github_copilot_token or os.environ.get("GITHUB_COPILOT_TOKEN", "")
        return OpenAIModel(
            client_args={
                "api_key": copilot_token,
                "base_url": "https://api.githubcopilot.com",
            },
            model_id=settings.github_copilot_model,
            params={"max_tokens": 4096},
        )
    return BedrockModel(
        model_id=settings.bedrock_model_id,
        region_name=settings.aws_region,
        max_tokens=4096,
    )


# ---------------------------------------------------------------------------
# Agent factory
# ---------------------------------------------------------------------------

def create_agent(client: AzureDevOpsClient, settings: Settings) -> Agent:
    """Assemble the CAPE BAU Support Agent with all tools wired up.

    Tools are created as closures over *client* and *settings* so they share
    the same authenticated session and policy flags for the entire run.

    Model provider is chosen by _build_model() (settings.model_provider,
    default 'bedrock') — see that function's docstring for the reasoning.
    """
    tools = [
        *create_ado_tools(client, settings),   # fetch_ado_ticket, add_comment, set_tag
        *create_wiki_tools(client),             # get_wiki_page_for_dqc, get_wiki_page, search_wiki
    ]
    model = _build_model(settings)
    return Agent(
        model=model,
        system_prompt=CAPE_BAU_AGENT_SYSTEM_PROMPT,
        tools=tools,
    )


def create_triage_agent(client: AzureDevOpsClient, settings: Settings) -> Agent:
    """Assemble the triage-stage agent — steps 1-3 of the bau-task-analysis skill.

    Deliberately narrower than create_agent():
    - No write tools (add_comment_to_ticket, set_azure_devops_ticket_ai_checked_tag)
      are exposed at all, not just policy-guarded — triage never writes to ADO,
      so there is no reason to even offer the tool and spend tokens describing it.
    - Uses CAPE_BAU_TRIAGE_SYSTEM_PROMPT (8-class taxonomy + needs_deep_analysis),
      not the single-stage CAPE_BAU_AGENT_SYSTEM_PROMPT.

    Model provider is chosen by _build_model() (settings.model_provider,
    default 'bedrock', default model settings.bedrock_model_id — a cheap,
    fast model is the whole point of a separate triage stage). See the
    two-stage handoff (2026-09-04) for the reasoning: triage is read-and-lookup,
    not a reasoning problem, so an o-series/reasoning model would be the wrong
    tool here.
    """
    tools = [
        *create_ado_tools(client, settings, include_write_tools=False),  # fetch_ado_ticket only
        *create_wiki_tools(client),
    ]
    model = _build_model(settings)
    return Agent(
        model=model,
        system_prompt=CAPE_BAU_TRIAGE_SYSTEM_PROMPT,
        tools=tools,
        # Suppress Strands' default PrintingCallbackHandler, which streams the
        # model's raw response (and every tool call) to stdout. Without this,
        # --triage-only emits the model's fenced ```json block first and the
        # parsed JSON second, so a caller piping stdout into a JSON parser
        # gets two documents and fails — breaking the contract documented in
        # main() below and in the kit's agentInstructions.
        callback_handler=None,
    )


# ---------------------------------------------------------------------------
# Runtime — triage stage
# ---------------------------------------------------------------------------

def run_triage(work_item_id: int) -> dict:
    """Run only the triage stage on a single work item and return its raw JSON dict.

    Unlike run_agent(), this does NOT format a comment or post anything to ADO —
    it is meant to be invoked as an external process (subprocess/bash call) whose
    stdout the bau-task-analysis skill's step 0 parses to decide whether to
    continue into that skill's deep-analysis stage (steps 4-5, stronger model)
    at all.

    Flow:
        1. Settings() reads AZURE_DEVOPS_EXT_PAT and GITHUB_COPILOT_TOKEN from the
           environment. Fails fast if the PAT is missing.
        2. AzureDevOpsClient is opened as a context manager.
        3. create_triage_agent() assembles a narrow, read-only agent (no write
           tools even offered) on the cheap model from Settings.
        4. The response is parsed for the JSON object defined in
           prompts.CAPE_BAU_TRIAGE_SYSTEM_PROMPT §4. On parse failure, a safe
           fallback dict is returned instead of raising, so a scripted caller
           always gets valid JSON on stdout.

    Returns:
        The parsed triage result dict (classification, needs_deep_analysis,
        identifiers, stakeholders, wiki_finding, summary, success, next_steps).
    """
    settings = Settings()
    with AzureDevOpsClient(settings) as client:
        agent = create_triage_agent(client, settings)

        message = (
            f"Triage this BAU Task. Work item ID: {work_item_id}.\n"
            f"Fetch it, extract identifiers and stakeholders, classify it, decide "
            f"needs_deep_analysis, and return your structured JSON result."
        )
        response = agent(message)
        response_text = str(response)

        try:
            return _extract_json(response_text)
        except (ValueError, json.JSONDecodeError) as e:
            return {
                "classification": "Unknown",
                "classification_signals": "triage agent response could not be parsed",
                "needs_deep_analysis": True,
                "identifiers": {},
                "stakeholders": {},
                "wiki_finding": "not queried",
                "summary": "Triage agent returned a response but no structured JSON "
                           "result could be parsed.",
                "success": False,
                "next_steps": f"Check agent logs and re-run manually. Parse error: {e}",
            }


# ---------------------------------------------------------------------------
# Runtime — full single-stage flow (legacy path)
# ---------------------------------------------------------------------------

def run_agent(work_item_id: int) -> str:
    """Run the CAPE BAU Support Agent on a single work item end-to-end.

    Flow:
        1. Settings() reads AZURE_DEVOPS_EXT_PAT (and other vars) from the
           environment or a .env file. Fails fast if the PAT is missing.
        2. AzureDevOpsClient is opened as a context manager so the underlying
           requests.Session is always closed, even on error.
        3. The agent is assembled and called with a trigger message. Internally
           it will make tool calls (fetch ticket, look up wiki, etc.) until it
           has enough to produce its JSON result.
        4. The raw response text is parsed for a JSON object. If parsing fails
           (e.g. the model didn't follow the output schema), a fallback error
           result is constructed so the run always produces a comment.
        5. The JSON is rendered into a markdown comment string.
        6. If both ado_writes_enabled and ado_comments_write_enabled are True
           in Settings, the comment is posted to ADO. Otherwise it is only
           printed (dry-run mode — the default when both flags are False).

    Returns:
        The formatted comment string (whether or not it was posted).
    """
    settings = Settings()
    with AzureDevOpsClient(settings) as client:
        agent = create_agent(client, settings)

        # The trigger message tells the agent which ticket to work on.
        # The system prompt (prompts.py) defines what to do with it.
        message = (
            f"A new BAU Task has been created in ADO. Work item ID: {work_item_id}.\n"
            f"Please analyse the ticket, look up any relevant wiki pages, "
            f"and return your structured JSON result."
        )
        response = agent(message)
        response_text = str(response)

        # Parse the JSON result from the agent's response text.
        # If parsing fails, construct a safe fallback so the run still produces output.
        try:
            result = _extract_json(response_text)
        except (ValueError, json.JSONDecodeError) as e:
            result = {
                "success": False,
                "summary": "Agent returned a response but no structured JSON result could be parsed.",
                "failure_cause": str(e),
                "next_steps": "Check agent logs and re-run manually.",
            }

        comment = _format_comment(result)

        # Post the comment only when both write flags are enabled.
        # Default: both are False → dry-run, comment is printed but not posted.
        if settings.ado_writes_enabled and settings.ado_comments_write_enabled:
            client.add_comment(work_item_id, comment)

        return comment


# ---------------------------------------------------------------------------
# CLI entry point
# ---------------------------------------------------------------------------

if __name__ == "__main__":
    # Minimal CLI: accepts a single work item ID as a positional argument, and
    # an optional --triage-only flag for the two-stage pipeline.
    # For production use, this entry point would be replaced by a webhook
    # handler or Lambda function that passes the ID from the ADO service hook.
    if len(sys.argv) < 2:
        print("Usage: python3 agent.py <work_item_id> [--triage-only]")
        print("Example: python3 agent.py 38512")
        print("Example: python3 agent.py 38512 --triage-only")
        sys.exit(1)

    wid = int(sys.argv[1])
    triage_only = "--triage-only" in sys.argv[2:]

    if triage_only:
        # Prints ONLY the JSON result to stdout (no banners) so a caller
        # (opencode command/bash tool) can pipe stdout straight into a JSON
        # parser without stripping anything.
        result = run_triage(wid)
        print(json.dumps(result, ensure_ascii=False, indent=2))
    else:
        print(f"\nRunning CAPE BAU Support Agent on work item #{wid}...\n")
        comment = run_agent(wid)
        print("\n--- Agent Comment ---")
        print(comment)
